function makeMistakes(seed: TopicSeed) {
  const baseKey = `unit1_${seed.slug.replaceAll("-", "_")}`;
  return [
    {
      mistakeKey: `${baseKey}_trap_1`,
      title: `${seed.title}: first trap`,
      description: seed.misconceptionA,
      correction: `Return to the anchor idea: ${seed.focus}`,
      example: seed.example,
      severity: seed.difficulty === "advanced" ? "high" : "medium",
    },
    {
      mistakeKey: `${baseKey}_trap_2`,
      title: `${seed.title}: second trap`,
      description: seed.misconceptionB,
      correction: "Ask what quantity, particle, ratio, or condition is actually being compared.",
      example: seed.example,
      severity: seed.difficulty === "beginner" ? "low" : "medium",
    },
  ] as const;
}

