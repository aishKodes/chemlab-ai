export function getPublishableOpenResources() {
  return openResourceCandidates.filter(
    (resource) =>
      resource.publicStatus === "published" &&
      resource.sourceUrl &&
      resource.licenseType &&
      resource.attributionText &&
      resource.licenseReviewed &&
      (resource.accuracyReviewStatus === "reviewed" || resource.accuracyReviewStatus === "verified"),
  );
}
