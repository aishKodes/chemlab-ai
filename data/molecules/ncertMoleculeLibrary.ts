function coordination(id: string, name: string, formula: string, metal: "Ni" | "Co" | "Fe" | "Cu", ligand: "CN" | "Cl" | "NH3", geometry: "Square planar" | "Tetrahedral" | "Octahedral", charge: string): NcertMolecule {
  const positions = geometry === "Octahedral" ? octahedralSubstituents(1.35) : geometry === "Square planar" ? squarePlanarSubstituents(1.3) : tetrahedralSubstituents(0.95);
  const ligandElement = ligand === "Cl" ? "Cl" : ligand === "CN" ? "C" : "N";
  return simple({
    id,
    name,
    formula,
    classLevels: ["12"],
    chapters: ["Coordination Compounds"],
    topics: ["Coordination geometry", "Crystal field theory"],
    categories: ["coordination", "inorganic"],
    coordinateSource: "idealized_vsepr",
    accuracyLevel: "idealized",
    geometry,
    hybridization: geometry === "Octahedral" ? "idealized octahedral field" : geometry === "Square planar" ? "idealized square planar field" : "idealized tetrahedral field",
    bondAngles: geometry === "Tetrahedral" ? ["about 109.5°"] : geometry === "Square planar" ? ["90°", "180°"] : ["90°", "180°"],
    atoms: [atom(metal, metal, [0, 0, 0], { charge, role: "central" }), ...positions.map((position, index) => atom(`${ligand}${index + 1}`, ligandElement, position, { label: ligand, role: "ligand" }))],
    bonds: positions.map((_, index) => bond(metal, `${ligand}${index + 1}`)),
    notes: "Idealized coordination geometry for Class 12 shape comparison. Ligands are simplified as donor atoms/cards, not full ligand conformers.",
  });
}

