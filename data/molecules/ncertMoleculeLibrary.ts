function ax4(id: string, name: string, formula: string, central: string, terminal: string, classLevels: NcertMolecule["classLevels"], topics: string[], categories: NcertMolecule["categories"] = ["vsepr", "inorganic"]): NcertMolecule {
  const positions = tetrahedralSubstituents();
  return vsepr({
    id,
    name,
    formula,
    classLevels,
    topics,
    categories,
    geometry: "Tetrahedral",
    hybridization: "sp3",
    bondAngles: ["about 109.5°"],
    atoms: [atom(central, central, [0, 0, 0], { role: "central" }), ...positions.map((position, index) => atom(`${terminal}${index + 1}`, terminal, position, { role: "terminal" }))],
    bonds: positions.map((_, index) => bond(central, `${terminal}${index + 1}`)),
  });
}

function linearDiatomic(id: string, name: string, formula: string, element: string, order: 1 | 2 | 3, classLevels: NcertMolecule["classLevels"], topics: string[]): NcertMolecule {
  return simple({
    id,
    name,
    formula,
    classLevels,
    topics,
    categories: ["inorganic"],
    coordinateSource: "hand_curated",
    geometry: "Linear diatomic",
    hybridization: order === 3 ? "triple bond" : order === 2 ? "double bond" : "single bond",
    bondAngles: ["180°"],
    atoms: [atom(`${element}1`, element, [-0.55, 0, 0]), atom(`${element}2`, element, [0.55, 0, 0])],
    bonds: [bond(`${element}1`, `${element}2`, order)],
    notes: "School-level diatomic model with idealized bond axis.",
  });
}

function hydrocarbonChain(id: string, name: string, formula: string, carbons: number, doubleAt?: number, tripleAt?: number): NcertMolecule {
  const carbonAtoms = chainAtoms(carbons);
  const carbonBonds = chainBonds(carbons, "C", doubleAt, tripleAt);
  const { atoms, bonds } = attachSimpleHydrogens(carbonAtoms, carbonBonds, tripleAt ? 1 : 3);
  const geometry = tripleAt ? "Linear around triple-bond carbons" : doubleAt ? "Planar around double-bond carbons" : "Zigzag tetrahedral carbon chain";
  return simple({
    id,
    name,
    formula,
    classLevels: ["10", "11"],
    chapters: ["Carbon and Its Compounds", "Hydrocarbons"],
    topics: ["Hydrocarbons", doubleAt ? "Alkenes" : tripleAt ? "Alkynes" : "Alkanes"],
    categories: ["organic", "hydrocarbon"],
    coordinateSource: "idealized_vsepr",
    accuracyLevel: "idealized",
    geometry,
    hybridization: tripleAt ? "sp at triple bond" : doubleAt ? "sp2 at double bond" : "sp3 carbon centres",
    bondAngles: tripleAt ? ["180° near triple bond"] : doubleAt ? ["about 120° near double bond"] : ["about 109.5° around saturated carbons"],
    atoms,
    bonds,
    notes: "Idealized hydrocarbon model. Hydrogens are arranged for readable school-level visualization, not conformer prediction.",
  });
}

